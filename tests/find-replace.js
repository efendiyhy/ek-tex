'use strict';
const assert=require('node:assert/strict'),fs=require('fs'),path=require('path');
const {occurrences,applyOne,applyAll}=require('../public/find-replace-core.js');
const root=path.join(__dirname,'..');
assert.deepEqual(occurrences('Ala ala ALA','ala').map(x=>x.start),[0,4,8]);
assert.deepEqual(occurrences('Ala ala ALA','ala',{caseSensitive:true}).map(x=>x.start),[4]);
assert.deepEqual(occurrences('cat catfish (cat)','cat',{wholeWord:true}).map(x=>x.start),[0,13]);
assert.deepEqual(occurrences('\\section{} \\section{}','\\section{}').map(x=>x.start),[0,11]);
assert.deepEqual(occurrences('test .* / test .*','.*').map(x=>x.start),[5,15]);
assert.equal(applyOne('one two', {start:4,end:7},'three'),'one three');
assert.deepEqual(applyAll('One one ONE',occurrences('One one ONE','one'),'two'),{content:'two two two',count:3});
assert.deepEqual(applyAll('x x',occurrences('x x','x'),'$1'),{content:'$1 $1',count:2});
assert.equal(occurrences('foo','').length,0);
const html=fs.readFileSync(path.join(root,'public/index.html'),'utf8'),app=fs.readFileSync(path.join(root,'public/app.js'),'utf8'),css=fs.readFileSync(path.join(root,'public/ai-assistant.css'),'utf8'),ai=fs.readFileSync(path.join(root,'public/ai-assistant.js'),'utf8');
for(const id of ['find-input','replace-input','replace-one','replace-all','find-prev','find-next','find-case','find-word','ai-launcher','ai-drawer'])assert(html.includes(`id="${id}"`),`Missing ${id}`);
assert(app.includes("key.toLowerCase()==='h'"));assert(app.includes('function replaceEvery()'));
assert(ai.includes("'ai-launcher'"));assert(css.includes('.ai-popup{top:auto'));
assert(!html.includes('Rekomendasi AI hanya membantu'));
console.log('[PASS] literal find, replace current/all, options, floating AI chat, simplified references');
