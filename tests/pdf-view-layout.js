'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
const html=read('public/index.html'),js=read('public/app.js'),css=read('public/workspace-refinement.css');
for(const id of ['pdf-view-split','pdf-view-tab','pdf-header-new-tab','editor-compile','editor-clean','editor-stop'])assert(html.includes(`id="${id}"`),`missing ${id}`);
assert(html.includes('aria-pressed="false"'),'view selector must have selection state');
assert(html.includes('/workspace-refinement.css'),'refinement stylesheet must be loaded');
assert(!html.includes('GETTING STARTED')&&!html.includes('id="help-compile"'),'remove old getting started card');
assert(js.includes('function setPdfView(')&&js.includes('function openPdfTab('),'two preview layouts must be handled');
assert(js.includes("window.open('about:blank',pdfWindowName(projectId))"),'reserve browser tab before asynchronous compilation');
assert(js.includes("$('editor-compile').onclick=()=>buildPdf(false)"),'keep compile action in new tab view');
assert(js.includes("$('editor-clean').onclick=()=>buildPdf(true)"),'keep clean action in new tab view');
assert(js.includes("$('editor-stop').onclick=()=>$('stop-compile').click()"),'keep stop action in new tab view');
assert(css.includes('scrollbar-color:var(--scroll-thumb) var(--scroll-track)'),'theme native scrollbars');
assert(css.includes('body[data-mode="light"]')&&css.includes('body[data-mode="dark"]'),'dual light/dark scrollbar variables');
assert(css.includes('.workspace.pdf-tab-mode .preview{display:none!important}'),'new tab view expands editor');
assert(css.includes('border-radius:20px'),'rounded panels');
console.log('[PASS] PDF split/new tab controls, reserved tab, source build actions, rounded themed UI, and no old getting started card');
